"""The handbook's look, chosen once and used everywhere: `handbook.theme` in the library's config.

`knowlib style` opens a picker page (palettes, typefaces, heading and table styles, figure boxes)
with a live sample; the page gives a `knowlib style --apply '...'` command that saves the choice.
From then on the PDF's style, the figures a model draws and the shared Typst style of hand-specified
figures (`figures/style.typ`) all follow it.
"""
from __future__ import annotations

import json
import re
import shlex
import shutil
from importlib import resources
from pathlib import Path

import yaml

DEFAULT = {"palette": None, "main": "#5a0f1b", "accent": "#3a3a3a", "tint": "#f3eff0",
           "body_font": "Georgia", "heading_font": None,
           "headings": "num", "table_header": "main", "boxes": "rounded", "box_fill": "tintline",
           "line_weight": "regular"}
CHOICES = {"headings": ("num", "all", "rule", "block"), "table_header": ("main", "accent", "line", "tint"),
           "boxes": ("rounded", "square", "pill"), "box_fill": ("tintline", "outline", "solid"),
           "line_weight": ("fine", "regular", "bold")}
COLOURS = ("main", "accent", "tint")
NAMES = ("palette", "body_font", "heading_font")
HEX = re.compile(r"#[0-9a-fA-F]{6}")
NAME = re.compile(r"[A-Za-z0-9 ._&-]{1,60}")          # no quotes, braces or semicolons: it goes into CSS and Typst
LINE_PT = {"fine": 0.4, "regular": 0.55, "bold": 0.8}
MARK = "// Generated by knowlib from handbook.theme (knowlib style). Edits here are overwritten."


def chosen(cfg: dict) -> dict | None:
    """The library's own theme settings, or None when it has not chosen one."""
    return ((cfg or {}).get("handbook") or {}).get("theme") or None


def resolve(theme: dict | None) -> dict:
    """The full theme: the library's choices over the defaults. Raises ValueError on a bad value."""
    out = dict(DEFAULT)
    for key, value in (theme or {}).items():
        if key not in DEFAULT:
            raise ValueError(f"handbook.theme: unknown setting {key!r}; use {', '.join(DEFAULT)}")
        if value is None or value == "":
            continue
        value = str(value).strip()
        if key in COLOURS and not HEX.fullmatch(value):
            raise ValueError(f"handbook.theme.{key}: {value!r} is not a colour like #5a0f1b")
        if key in NAMES and not NAME.fullmatch(value):
            raise ValueError(f"handbook.theme.{key}: {value!r} has characters a name cannot have")
        if key in CHOICES and value not in CHOICES[key]:
            raise ValueError(f"handbook.theme.{key}: {value!r}; use one of {', '.join(CHOICES[key])}")
        out[key] = value.lower() if key in COLOURS else value
    return out


def parse(settings: str) -> dict:
    """The picker's settings line (`main=#5a0f1b body_font="Iowan Old Style" ...`) as a theme."""
    theme = {}
    for part in shlex.split(settings):
        key, sep, value = part.partition("=")
        if not sep:
            raise ValueError(f"expected key=value, got {part!r}")
        theme[key.strip()] = value.strip()
    resolve(theme)
    return theme


def css(theme: dict) -> str:
    """Rules added after the library's handbook style, so the theme wins over what the style file says."""
    t = resolve(theme)
    body = f'"{t["body_font"]}", Georgia, serif'
    head = f'"{t["heading_font"]}", {body}' if t["heading_font"] else body
    rules = [
        "/* handbook.theme */",
        f':root {{ --main: {t["main"]}; --accent: {t["accent"]}; --tint: {t["tint"]}; }}',
        f"body, p, li, td, th, blockquote, figcaption, table caption, h1::after, h3, math, .kl-sign-off, .kl-tagline "
        f"{{ font-family: {body}; }}",
        f"h1, h2, .kl-byline {{ font-family: {head}; }}",
        f'@page {{ @bottom-right {{ color: {t["main"]}; font-family: {body}; }} '
        f"@bottom-center {{ font-family: {body}; }} }}",
        "h1, strong, .kl-byline { color: var(--main); } li::marker { color: var(--main); }",
        "th { background: var(--main); color: #fff; }",
    ]
    rules += {
        "num": [],
        "all": ["h2 { color: var(--main); }"],
        "rule": ["h2 { border-bottom: .5pt solid var(--main); padding-bottom: .5mm; }"],
        "block": ["body { counter-reset: sec; } h2 { counter-increment: sec; }",
                  "h2::before { content: counter(sec); background: var(--main); color: #fff; "
                  "padding: 0 1.3mm; margin-right: 1.6mm; }"],
    }[t["headings"]]
    rules += {
        "main": [],
        "accent": ["th { background: var(--accent); }"],
        "line": ["th { background: none; color: var(--main); border-bottom: 1.2pt solid var(--main); }"],
        "tint": ["th { background: var(--tint); color: var(--main); border-bottom: .8pt solid var(--main); }"],
    }[t["table_header"]]
    return "\n".join(rules) + "\n"


def typst_style(theme: dict | None) -> str:
    """The shared style file that hand-specified figures import (`#import "../style.typ": *`)."""
    t = resolve(theme)
    text = resources.files("knowlib").joinpath("templates/figure-style.typ").read_text(encoding="utf-8")
    values = {"MAIN": t["main"], "ACCENT": t["accent"], "TINT": t["tint"], "FONT": t["body_font"],
              "LINE": f'{LINE_PT[t["line_weight"]]}pt', "BOX_FILL": t["box_fill"],
              "CORNER": "0" if t["boxes"] == "square" else "1.2", "PILL": "true" if t["boxes"] == "pill" else "false"}
    for key, value in values.items():
        text = text.replace("{{" + key + "}}", value)
    return MARK + "\n" + text


def sync_figure_style(figures: Path, theme: dict | None, force: bool = False) -> Path | None:
    """Write `figures/style.typ` when it is missing or was generated by knowlib and is out of date.
    A style file someone wrote by hand is left alone unless force is set."""
    path = figures / "style.typ"
    new = typst_style(theme)
    if path.exists():
        old = path.read_text(encoding="utf-8")
        if old == new or (not old.startswith(MARK) and not force):
            return None
    path.write_text(new, encoding="utf-8")
    return path


def picker(root: Path, cfg: dict) -> Path:
    """Write the picker page for this library, with its current theme selected, and return its path."""
    page = resources.files("knowlib").joinpath("templates/style-picker.html").read_text(encoding="utf-8")
    current = resolve(chosen(cfg))
    page = page.replace("/*KNOWLIB_THEME*/null", json.dumps(current).replace("</", "<\\/"))
    page = page.replace('/*KNOWLIB_LIBRARY*/""', json.dumps(str(root)).replace("</", "<\\/"))
    out = root / "_knowlib" / "work" / "style-picker.html"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(page, encoding="utf-8")
    return out


def save(root: Path, theme: dict) -> Path:
    """Put the theme under `handbook:` in the library's config.yaml, changing nothing else in the file
    (comments included) and keeping a backup. Refuses if the result would not read back as intended."""
    from ..config import config_path
    full = resolve(theme)
    wanted = {k: v for k, v in full.items() if v is not None}
    path = config_path(Path(root).expanduser().resolve())
    text = path.read_text(encoding="utf-8") if path.exists() else ""
    before = yaml.safe_load(text) or {}
    block = ["  theme:                   # the handbook's look; chosen with `knowlib style`"]
    block += [f"    {k}: {json.dumps(v, ensure_ascii=False)}" for k, v in wanted.items()]
    lines = text.splitlines()
    start = next((i for i, ln in enumerate(lines) if re.match(r"handbook:\s*(#.*)?$", ln)), None)
    if start is None:
        lines += ([""] if lines and lines[-1].strip() else []) + ["handbook:"] + block
    else:
        end = next((i for i in range(start + 1, len(lines)) if lines[i].strip() and not lines[i].startswith((" ", "#"))),
                   len(lines))
        while end > start + 1 and not lines[end - 1].strip():
            end -= 1                                             # keep blank lines after the section
        a = next((i for i in range(start + 1, end) if re.match(r"  theme:", lines[i])), None)
        if a is None:
            lines[end:end] = block
        else:
            b = next((i for i in range(a + 1, end) if lines[i].strip() and not lines[i].startswith("    ")), end)
            lines[a:b] = block
    new = "\n".join(lines) + "\n"
    after = yaml.safe_load(new) or {}
    got = (after.get("handbook") or {}).get("theme")
    rest = {**after, "handbook": {k: v for k, v in (after.get("handbook") or {}).items() if k != "theme"}}
    was = {**before, "handbook": {k: v for k, v in (before.get("handbook") or {}).items() if k != "theme"}}
    if got != wanted or rest != was:
        raise ValueError(f"could not add the theme to {path} safely; add this under `handbook:` by hand:\n"
                         + "\n".join(block))
    if path.exists():
        shutil.copy2(path, path.with_suffix(".yaml.bak"))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(new, encoding="utf-8")
    return path
